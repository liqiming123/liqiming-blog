// 去掉行政后缀再查表，兼容「广东省/黑龙江省/广西壮族自治区」等写法
function normalizeRegion(name) {
  return String(name || '')
    .replace(/(特别行政区|维吾尔|壮族|回族|自治区|省|市|区)/g, '')
    .trim()
}

// name 含有 key 即命中，处理「中国|河南省|洛阳市|联通」这类带前缀的写法
function lookup(dict, name) {
  const key = normalizeRegion(name)
  if (dict[key]) return { coord: dict[key], region: key }
  const hit = Object.keys(dict).find(k => key === k || key.includes(k) || k.includes(key) && key.length >= 2)
  return hit ? { coord: dict[hit], region: hit } : null
}

export function isChinaRegion(name) {
  const text = String(name || '')
  return text.includes('中国') || !!lookup(PROVINCE_COORDS, text)
}

/**
 * 把后端地域聚合数据 [{ name, value }] 转成地球仪坐标点。
 * 命中中国省份 → 省份质心；命中国家 → 国家质心；两者都未命中 → unmatched。
 */
export function parseGeoPoints(rows) {
  const points = []
  const unmatched = []
  for (const row of rows || []) {
    const name = row.name || row.provinceName || row.areaName || row.regionName || '未知'
    const value = Number(row.value || row.count || row.userCount || 0)
    const china = lookup(PROVINCE_COORDS, name)
    const country = china ? null : lookup(COUNTRY_COORDS, name)
    if (china || country) {
      points.push({ name: (china ? '中国 · ' : '') + name, value, coord: (china || country).coord })
    } else {
      unmatched.push({ name, value })
    }
  }
  return { points, unmatched }
}
